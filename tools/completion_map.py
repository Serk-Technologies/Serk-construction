#!/usr/bin/env python3
"""Generates docs/completion/02_DOMAIN_MAP.md and 03_REQUIREMENTS_TRACEABILITY.md
from docs/engineering/requirements.json, so the completion plan and the
traceability view cannot disagree with the requirement register.

The only hand-written content is WAVES below: the order in which the 80
domains are to be built and what each wave depends on. Statuses, counts and
evidence come from the register.

usage: python3 tools/completion_map.py
"""
import collections
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# (wave, title, domains, depends on, what unblocks it / who must decide)
WAVES = [
    ("W0", "Governance and trusted integration", [],
     "nothing", "Branch protection on main and a reviewed pull request: repository administrator."),
    ("W1", "Fleet completion on the existing stock ledger and journal", ["FLT-02", "FLT-03", "FLT-04", "FLT-01"],
     "stock ledger, job cost, journal (built)", "Charge-out and depreciation policies: financial controller."),
    ("W2", "Site execution: work packages, measurement, permits, constraints", ["PLB-05", "PLB-03", "PLB-04", "PLB-06", "PLB-07", "PLB-08", "PLB-02", "PLB-01"],
     "WBS, schedule, BOQ, site diary (built)", "Measurement and certification rules: quantity surveying reviewer."),
    ("W3", "Quality, laboratory, HSE", ["ASR-01", "ASR-02", "ASR-03", "ASR-04"],
     "W2 work packages; controlled documents (built)", "Workflow acceptance: quality and HSE professionals. Safety decisions stay human."),
    ("W4", "Supply chain remainder", ["SUP-04", "SUP-07", "SUP-08", "SUP-01", "SUP-02", "SUP-03", "SUP-05", "SUP-06", "SUP-09"],
     "procure-to-pay and stock (built)", "Supplier evaluation criteria: procurement manager."),
    ("W5", "Contracts and commercial remainder", ["CON-01", "CON-02", "CON-03", "CON-04", "PLB-09"],
     "contracts, variations, claims, IPC (built)", "Revenue and retention policies: financial controller; contract forms: legal."),
    ("W6", "Estimating and tendering", ["EST-06", "EST-07", "EST-05", "EST-01", "EST-02", "EST-03", "EST-04"],
     "BOQ and budget (built); W4 supplier prices", "Rate libraries and productivity norms must be supplied by the business; none are invented."),
    ("W7", "Finance remainder: bank, treasury, fixed assets, consolidation, close", ["CAP-01", "CAP-02", "CAP-03", "CAP-04", "CAP-05", "CAP-08", "CAP-09", "CAP-06", "CAP-07"],
     "ledger (built); W1 for fixed assets", "Accounting policies: CFO. Tax rules: tax specialist (CAP-06 is blocked on that). Bank integration needs a bank's authorised interface."),
    ("W8", "People and payroll", ["PPL-01", "PPL-02", "PPL-04", "PPL-05", "PPL-03"],
     "organisation and projects (built); W7 for payroll postings", "Statutory payroll, pension and labour rules must be professionally supplied and approved (PPL-03 blocked). No rate is invented."),
    ("W9", "Common data environment remainder and portals", ["CNX-01", "CNX-02", "CNX-03", "CNX-04", "CNX-05", "CNX-08", "CNX-10", "CNX-11", "CNX-12", "CNX-06", "CNX-07", "CNX-09", "CNX-13"],
     "documents and RFIs (built)", "External portals need an identity provider for external users. Government interfaces need official specifications (CNX-13 blocked)."),
    ("W10", "Estate: property, sales, handover, facilities", ["RES-01", "RES-02", "RES-03", "RES-04"],
     "contracts, receivables, documents (built)", "Sales contract forms: legal."),
    ("W11", "Design: BIM, GIS, digital twin relationships", ["DSN-01", "DSN-02", "DSN-03"],
     "documents (built); W2 for progress", "Choice and licensing of an IFC library: architecture decision. No authoring or clash detection is claimed."),
    ("W12", "Command, intelligence and platform", ["CMD-01", "CMD-02", "CMD-03", "CMD-04", "CMD-05", "BRS-01", "BRS-02", "BRS-03", "BRS-04"],
     "every wave above for their indicators", "A model provider, credentials and a data-sharing policy must be authorised by the owner before any real AI endpoint is used. Real identity provider and KMS/HSM: owner."),
]


def main():
    d = json.load(open(os.path.join(ROOT, "docs/engineering/requirements.json")))
    dom = {g["id"]: g for g in d["domains"]}
    planned = [x for w in WAVES for x in w[2]]
    missing = sorted(set(dom) - set(planned))
    extra = sorted(set(planned) - set(dom))
    dupes = [k for k, v in collections.Counter(planned).items() if v > 1]
    if missing or extra or dupes:
        raise SystemExit(f"plan and register disagree: missing {missing}, unknown {extra}, twice {dupes}")

    def counts(g):
        c = collections.Counter(r["status"] for r in g["requirements"])
        return c

    out = ["# Domain map and dependency-ordered completion plan", "",
           "Generated by `tools/completion_map.py` from `docs/engineering/requirements.json` (register generated from commit `%s`). Do not edit by hand." % d.get("generated_from_commit", d.get("commit", "?")), "",
           "Statuses are the register's: VERIFIED means the named automated tests passed; it is not human acceptance. A domain is never marked complete here: no owner has yet reviewed any domain's requirement list.", "",
           "## Totals", ""]
    rc = d["requirement_counts"]
    out.append("%d domains; %d requirements in total (%d in domains, %d cross-cutting): " % (
        len(dom), sum(rc.values()), sum(len(g["requirements"]) for g in d["domains"]), sum(len(g["requirements"]) for g in d["cross_cutting"]))
        + ", ".join("%s %d" % (k, v) for k, v in sorted(rc.items())) + ".")
    out += ["", "## Waves, in build order", "",
            "| Wave | Scope | Domains | Requirements verified / listed | Depends on | Needs a human decision or external input |", "|---|---|---|---|---|---|"]
    for w, title, ids, dep, human in WAVES:
        v = sum(counts(dom[i])["VERIFIED"] for i in ids)
        n = sum(len(dom[i]["requirements"]) for i in ids)
        out.append("| %s | %s | %s | %s | %s | %s |" % (w, title, ", ".join(ids) or "(repository)", ("%d / %d" % (v, n)) if ids else "n/a", dep, human))
    out += ["", "## Domains", "", "| Domain | Product | Area | Wave | Status | Verified | Implementing | Not started | Blocked |", "|---|---|---|---|---|---|---|---|---|"]
    wave_of = {i: w[0] for w in WAVES for i in w[2]}
    for g in d["domains"]:
        c = counts(g)
        out.append("| %s | %s | %s | %s | %s | %d | %d | %d | %d |" % (g["id"], g["product"], g["domain"], wave_of[g["id"]], g["status"],
                   c["VERIFIED"], c["IMPLEMENTING"] + c["IMPLEMENTED_UNVERIFIED"], c["NOT_STARTED"], c["BLOCKED"]))
    out += ["", "## Rules for every wave", "",
            "- One vertical slice at a time: schema with database invariants, kernel, API, permissions, console, tests (positive, negative, authorisation, concurrency), documentation, evidence.",
            "- Financial effects only through the existing posting interfaces; stock effects only through the existing stock ledger.",
            "- Statutory, tax, payroll and contractual rules are loaded only when a named professional has supplied and approved them.",
            "- An external service is verified only against the real, authorised service.", ""]
    open(os.path.join(ROOT, "docs/completion/02_DOMAIN_MAP.md"), "w").write("\n".join(out))

    t = ["# Requirements traceability", "",
         "Generated by `tools/completion_map.py` from `docs/engineering/requirements.json`, which is the machine-readable matrix (requirement, status, evidence tests, evidence file, note). Do not edit by hand.", "",
         "Status vocabulary in the register today: NOT_STARTED, IMPLEMENTING, IMPLEMENTED_UNVERIFIED, VERIFIED (automated verification), BLOCKED. No requirement is HUMAN_ACCEPTED: no authorised person has accepted any.", ""]
    for g in d["domains"] + d["cross_cutting"]:
        t += ["## %s %s" % (g["id"], " — ".join(x for x in (g.get("product"), g.get("domain")) if x)), "",
              "| Requirement | Status | Evidence (tests) | Limitation or note |", "|---|---|---|---|"]
        for r in g["requirements"]:
            ev = ", ".join("`%s`" % x for x in (r.get("evidence_tests") or [])) or (r.get("evidence_file") or "")
            t.append("| %s %s | %s | %s | %s |" % (r["id"], r["text"].replace("|", "/"), r["status"], ev, (r.get("note") or "").replace("|", "/")))
        t.append("")
    open(os.path.join(ROOT, "docs/completion/03_REQUIREMENTS_TRACEABILITY.md"), "w").write("\n".join(t))
    print("waves", len(WAVES), "domains", len(dom))


if __name__ == "__main__":
    main()
