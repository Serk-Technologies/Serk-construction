#!/usr/bin/env python3
"""Computes WCAG 2.x contrast ratios for the foreground/background pairs the
AURA tokens are actually used in, and fails if a pair misses its target.

usage: python3 tools/design/aura_contrast.py [--write docs/design/aura/CONTRAST.md]

Targets: 4.5:1 for body text, 3:1 for large text and for the boundaries of
interface components and focus indicators (WCAG 2.2 SC 1.4.3, 1.4.11).
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def lum(hexcolor):
    h = hexcolor.lstrip("#")
    out = []
    for i in (0, 2, 4):
        c = int(h[i:i + 2], 16) / 255
        out.append(c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4)
    return 0.2126 * out[0] + 0.7152 * out[1] + 0.0722 * out[2]


def ratio(a, b):
    la, lb = lum(a), lum(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


def css_blocks(css):
    """The console declares its variables in three blocks: :root (light), the
    prefers-color-scheme dark block and :root[data-theme="dark"]."""
    import re
    def block(start):
        i = css.index(start)
        j = css.index("}", css.index("{", i + len(start) - 1) if "{" not in start else i + len(start))
        return dict(re.findall(r"--([a-z0-9-]+):\s*(#[0-9a-fA-F]{6})\s*;", css[i:j]))
    return {"light": block(":root {"), "dark (system)": block(':root:not([data-theme="light"]) {'), "dark": block(':root[data-theme="dark"] {')}


def check_css(tokens):
    css = open(os.path.join(ROOT, "internal/webui/static/app.css"), encoding="utf-8").read()
    blocks, bad = css_blocks(css), 0
    for name, theme in (("light", "light"), ("dark (system)", "dark"), ("dark", "dark")):
        want = tokens["themes"][theme]["console"]
        for var, value in want.items():
            got = blocks[name].get(var)
            if got is None or got.lower() != value.lower():
                print("  CSS %s: --%s is %s, tokens say %s" % (name, var, got, value))
                bad += 1
    return bad


def main():
    tokens = json.load(open(os.path.join(ROOT, "docs/design/aura/tokens.json")))
    rows, failed = [], 0
    for theme, t in tokens["themes"].items():
        c = t["color"]
        for fg, bg, need, use in tokens["contrast_pairs"]:
            if fg not in c or bg not in c:
                continue
            r = ratio(c[fg], c[bg])
            ok = r >= need
            failed += not ok
            rows.append((theme, fg, c[fg], bg, c[bg], r, need, "pass" if ok else "FAIL", use))
        k = t.get("console", {})
        for fg, bg, need, use in tokens.get("console_pairs", []):
            if fg not in k or bg not in k:
                continue
            r = ratio(k[fg], k[bg])
            ok = r >= need
            failed += not ok
            rows.append((theme + " (console)", "--" + fg, k[fg], "--" + bg, k[bg], r, need, "pass" if ok else "FAIL", use))
    if "--check-css" in sys.argv:
        failed += check_css(tokens)
    lines = ["# AURA contrast check", "",
             "Generated by `tools/design/aura_contrast.py` from `tokens.json`. Ratios are computed (WCAG 2.x relative luminance), not estimated.", "",
             "| Theme | Foreground | Background | Ratio | Needed | Result | Used for |", "|---|---|---|---|---|---|---|"]
    for theme, fg, fgc, bg, bgc, r, need, res, use in rows:
        lines.append("| %s | %s `%s` | %s `%s` | %.2f:1 | %.1f:1 | %s | %s |" % (theme, fg, fgc, bg, bgc, r, need, res, use))
    text = "\n".join(lines) + "\n"
    if "--write" in sys.argv:
        open(os.path.join(ROOT, sys.argv[sys.argv.index("--write") + 1]), "w").write(text)
    print("pairs %d, failed %d" % (len(rows), failed))
    for row in rows:
        if row[7] == "FAIL":
            print("  FAIL %s: %s on %s = %.2f, needs %.1f (%s)" % (row[0], row[1], row[3], row[5], row[6], row[8]))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
