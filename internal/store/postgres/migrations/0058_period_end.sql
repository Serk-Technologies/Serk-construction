-- 0058 Period-end: recurring journals, accruals that reverse, overhead
-- allocation (WP-2.13; SRS FIN-10, FIN-11, FIN-12)
--
-- WHAT THIS MIGRATION DOES
--   * RECURRING JOURNAL: a template (entity, optional project, balanced lines,
--     a day of the month, the next date and an optional end) from which the
--     kernel creates the month's DRAFT journal, once per template and date
--     (recurring_journal_runs is unique on both). The journals then follow the
--     ordinary approval and posting with segregation of duties.
--   * ACCRUAL: a journal marked to reverse on a later date (normally the first
--     day of the next period). Once it is POSTED, the kernel creates its
--     reversal on that date (once) through the ordinary reversal path.
--   * OVERHEAD ALLOCATION: the posted balance of an overhead pool account for a
--     date range is spread over the entity's projects in proportion to their
--     posted direct cost in that range (expense accounts other than the pool
--     and the target). The database computes the shares (cents rounded, the
--     remainder to the largest share) and refuses lines that differ; the
--     kernel creates one DRAFT journal per project (Dr the overhead-applied
--     account on the project / Cr the pool).
--   (Fiscal years, Gregorian or Ethiopian, are generated by the kernel as
--   ordinary OPEN fiscal periods; no schema change is needed.)

CREATE TABLE recurring_journals (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id       uuid NOT NULL DEFAULT current_tenant() REFERENCES tenants(id),
  legal_entity_id uuid NOT NULL,
  number          text NOT NULL,
  name            text NOT NULL CHECK (length(btrim(name)) BETWEEN 3 AND 200),
  project_id      uuid,
  day_of_month    integer NOT NULL CHECK (day_of_month BETWEEN 1 AND 28),
  next_run_on     date NOT NULL,
  ends_on         date,
  status          text NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'PAUSED', 'ENDED')),
  created_by      text NOT NULL,
  created_at      timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, id),
  UNIQUE (tenant_id, number),
  FOREIGN KEY (tenant_id, legal_entity_id) REFERENCES legal_entities(tenant_id, id),
  CONSTRAINT recurring_day_matches CHECK (extract(day FROM next_run_on) = day_of_month),
  CONSTRAINT recurring_end_after CHECK (ends_on IS NULL OR ends_on >= next_run_on OR status = 'ENDED')
);

CREATE TABLE recurring_journal_lines (
  tenant_id    uuid NOT NULL DEFAULT current_tenant() REFERENCES tenants(id),
  template_id  uuid NOT NULL,
  line_no      integer NOT NULL CHECK (line_no BETWEEN 1 AND 200),
  account_id   uuid NOT NULL,
  side         text NOT NULL CHECK (side IN ('DEBIT', 'CREDIT')),
  amount       numeric(24,6) NOT NULL CHECK (amount > 0),
  cost_code_id uuid,
  memo         text,
  PRIMARY KEY (tenant_id, template_id, line_no),
  FOREIGN KEY (tenant_id, template_id) REFERENCES recurring_journals(tenant_id, id)
);

CREATE TABLE recurring_journal_runs (
  tenant_id   uuid NOT NULL DEFAULT current_tenant() REFERENCES tenants(id),
  template_id uuid NOT NULL,
  run_on      date NOT NULL,
  journal_id  uuid NOT NULL UNIQUE,
  created_by  text NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (tenant_id, template_id, run_on),
  FOREIGN KEY (tenant_id, template_id) REFERENCES recurring_journals(tenant_id, id)
);

CREATE FUNCTION recurring_journals_guard() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, public, pg_temp AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.status <> 'ACTIVE' THEN
      RAISE EXCEPTION 'recurring journals are created ACTIVE' USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
  END IF;
  IF OLD.status = 'ENDED' THEN
    RAISE EXCEPTION 'an ended recurring journal never changes' USING ERRCODE = 'check_violation';
  END IF;
  PERFORM p2p_only_changed(to_jsonb(OLD), to_jsonb(NEW), ARRAY['status', 'next_run_on'], 'recurring journal');
  IF NEW.next_run_on < OLD.next_run_on THEN
    RAISE EXCEPTION 'a recurring journal never moves back in time' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.next_run_on > OLD.next_run_on AND NOT EXISTS (SELECT 1 FROM recurring_journal_runs WHERE template_id = NEW.id AND run_on = OLD.next_run_on) THEN
    RAISE EXCEPTION 'a recurring journal advances only after its run for % was recorded', OLD.next_run_on USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END$$;
CREATE TRIGGER recurring_journals_guard BEFORE INSERT OR UPDATE ON recurring_journals FOR EACH ROW EXECUTE FUNCTION recurring_journals_guard();

CREATE FUNCTION recurring_journal_lines_guard() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE r recurring_journals;
BEGIN
  SELECT * INTO r FROM recurring_journals WHERE id = NEW.template_id AND tenant_id = current_tenant();
  IF r.created_at < now() - interval '1 minute' OR EXISTS (SELECT 1 FROM recurring_journal_runs WHERE template_id = r.id) THEN
    RAISE EXCEPTION 'the lines of a recurring journal are written with it' USING ERRCODE = 'check_violation';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM accounts WHERE id = NEW.account_id AND legal_entity_id = r.legal_entity_id AND active) THEN
    RAISE EXCEPTION 'line % uses an account that is not an active account of the entity', NEW.line_no USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END$$;
CREATE TRIGGER recurring_journal_lines_guard BEFORE INSERT ON recurring_journal_lines FOR EACH ROW EXECUTE FUNCTION recurring_journal_lines_guard();

CREATE FUNCTION recurring_journal_runs_guard() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE r recurring_journals;
BEGIN
  SELECT * INTO r FROM recurring_journals WHERE id = NEW.template_id AND tenant_id = current_tenant();
  IF r.status <> 'ACTIVE' OR NEW.run_on <> r.next_run_on OR (r.ends_on IS NOT NULL AND NEW.run_on > r.ends_on) THEN
    RAISE EXCEPTION 'a recurring journal runs on its next date while active and not ended' USING ERRCODE = 'check_violation';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM journals j WHERE j.id = NEW.journal_id AND j.legal_entity_id = r.legal_entity_id AND j.source_type = 'RECURRING' AND j.source_ref = r.id::text
                   AND (j.business_event_at AT TIME ZONE 'UTC')::date = NEW.run_on) THEN
    RAISE EXCEPTION 'the run must record the template''s own journal for that date' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END$$;
CREATE TRIGGER recurring_journal_runs_guard BEFORE INSERT ON recurring_journal_runs FOR EACH ROW EXECUTE FUNCTION recurring_journal_runs_guard();

CREATE TABLE accruals (
  tenant_id           uuid NOT NULL DEFAULT current_tenant() REFERENCES tenants(id),
  journal_id          uuid NOT NULL,
  legal_entity_id     uuid NOT NULL,
  reverse_on          date NOT NULL,
  reversal_journal_id uuid UNIQUE,
  created_by          text NOT NULL,
  created_at          timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (tenant_id, journal_id)
);

CREATE FUNCTION accruals_guard() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE j journals;
BEGIN
  SELECT * INTO j FROM journals WHERE id = NEW.journal_id AND tenant_id = current_tenant();
  IF TG_OP = 'INSERT' THEN
    IF j.id IS NULL OR j.source_type <> 'ACCRUAL' OR j.status <> 'DRAFT' OR NEW.reversal_journal_id IS NOT NULL THEN
      RAISE EXCEPTION 'an accrual is recorded with its own new DRAFT ACCRUAL journal' USING ERRCODE = 'check_violation';
    END IF;
    IF NEW.reverse_on <= (j.business_event_at AT TIME ZONE 'UTC')::date THEN
      RAISE EXCEPTION 'an accrual reverses after its own date' USING ERRCODE = 'check_violation';
    END IF;
    NEW.legal_entity_id := j.legal_entity_id;
    RETURN NEW;
  END IF;
  PERFORM p2p_only_changed(to_jsonb(OLD), to_jsonb(NEW), ARRAY['reversal_journal_id'], 'accrual');
  IF OLD.reversal_journal_id IS NOT NULL OR NOT EXISTS (SELECT 1 FROM journals r WHERE r.id = NEW.reversal_journal_id AND r.reversal_of = OLD.journal_id
       AND (r.business_event_at AT TIME ZONE 'UTC')::date = OLD.reverse_on) THEN
    RAISE EXCEPTION 'an accrual is reversed once, by the reversal of its journal dated %', OLD.reverse_on USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END$$;
CREATE TRIGGER accruals_guard BEFORE INSERT OR UPDATE ON accruals FOR EACH ROW EXECUTE FUNCTION accruals_guard();

-- Overhead allocation: the pool's posted balance spread by posted direct cost.
CREATE FUNCTION overhead_compute(p_entity uuid, p_from date, p_to date, p_pool uuid, p_target uuid)
RETURNS TABLE (project_id uuid, driver numeric, share numeric)
LANGUAGE sql STABLE SET search_path = pg_catalog, public, pg_temp AS $$
  WITH e AS (SELECT currency_minor_units(functional_currency) AS mu FROM legal_entities WHERE id = p_entity AND tenant_id = current_tenant()),
  pool AS (SELECT COALESCE(sum(CASE WHEN l.side = 'DEBIT' THEN l.amount ELSE -l.amount END), 0) AS amt
             FROM journal_lines l JOIN journals j ON j.id = l.journal_id
            WHERE l.account_id = p_pool AND j.status IN ('POSTED', 'REVERSED') AND j.legal_entity_id = p_entity AND j.tenant_id = current_tenant()
              AND (j.business_event_at AT TIME ZONE 'UTC')::date BETWEEN p_from AND p_to AND j.source_type <> 'OVERHEAD'),
  d AS (SELECT l.project_id AS pid, sum(CASE WHEN l.side = 'DEBIT' THEN l.amount ELSE -l.amount END) AS drv
          FROM journal_lines l JOIN journals j ON j.id = l.journal_id JOIN accounts a ON a.id = l.account_id
         WHERE j.legal_entity_id = p_entity AND j.tenant_id = current_tenant() AND j.status IN ('POSTED', 'REVERSED') AND l.project_id IS NOT NULL
           AND a.type = 'EXPENSE' AND l.account_id NOT IN (p_pool, p_target) AND (j.business_event_at AT TIME ZONE 'UTC')::date BETWEEN p_from AND p_to
         GROUP BY l.project_id HAVING sum(CASE WHEN l.side = 'DEBIT' THEN l.amount ELSE -l.amount END) > 0),
  t AS (SELECT sum(drv) AS total FROM d),
  sh AS (SELECT d.pid, d.drv, round_half_even(pool.amt * d.drv / t.total, e.mu) AS amt FROM d, t, pool, e WHERE pool.amt > 0 AND t.total > 0),
  big AS (SELECT pid FROM d ORDER BY drv DESC, pid LIMIT 1)
  SELECT sh.pid, sh.drv, sh.amt + CASE WHEN sh.pid = (SELECT pid FROM big) THEN (SELECT amt FROM pool) - (SELECT sum(amt) FROM sh) ELSE 0 END
    FROM sh ORDER BY sh.pid
$$;

CREATE TABLE overhead_runs (
  id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id        uuid NOT NULL DEFAULT current_tenant() REFERENCES tenants(id),
  legal_entity_id  uuid NOT NULL,
  number           text NOT NULL,
  period_from      date NOT NULL,
  period_to        date NOT NULL CHECK (period_to >= period_from),
  pool_account_id  uuid NOT NULL,
  target_account_id uuid NOT NULL,
  amount           numeric(24,6) NOT NULL CHECK (amount > 0),
  created_by       text NOT NULL,
  created_at       timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, id),
  UNIQUE (tenant_id, number),
  FOREIGN KEY (tenant_id, legal_entity_id) REFERENCES legal_entities(tenant_id, id),
  CONSTRAINT overhead_accounts_differ CHECK (pool_account_id <> target_account_id)
);
CREATE UNIQUE INDEX overhead_runs_once ON overhead_runs (tenant_id, legal_entity_id, pool_account_id, period_from, period_to);

CREATE TABLE overhead_lines (
  tenant_id  uuid NOT NULL DEFAULT current_tenant() REFERENCES tenants(id),
  run_id     uuid NOT NULL,
  project_id uuid NOT NULL,
  driver     numeric(24,6) NOT NULL,
  share      numeric(24,6) NOT NULL CHECK (share > 0),
  journal_id uuid UNIQUE,
  PRIMARY KEY (tenant_id, run_id, project_id),
  FOREIGN KEY (tenant_id, run_id) REFERENCES overhead_runs(tenant_id, id)
);

CREATE FUNCTION overhead_runs_guard() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, public, pg_temp AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM accounts WHERE id = NEW.pool_account_id AND legal_entity_id = NEW.legal_entity_id AND type = 'EXPENSE' AND active)
     OR NOT EXISTS (SELECT 1 FROM accounts WHERE id = NEW.target_account_id AND legal_entity_id = NEW.legal_entity_id AND type = 'EXPENSE' AND active) THEN
    RAISE EXCEPTION 'the overhead pool and the overhead-applied account are active EXPENSE accounts of the entity' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.amount <> (SELECT COALESCE(sum(share), 0) FROM overhead_compute(NEW.legal_entity_id, NEW.period_from, NEW.period_to, NEW.pool_account_id, NEW.target_account_id)) THEN
    RAISE EXCEPTION 'the amount allocated must be the pool''s posted balance for the range' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END$$;
CREATE TRIGGER overhead_runs_guard BEFORE INSERT ON overhead_runs FOR EACH ROW EXECUTE FUNCTION overhead_runs_guard();

CREATE FUNCTION overhead_lines_guard() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE r overhead_runs; x record;
BEGIN
  SELECT * INTO r FROM overhead_runs WHERE id = NEW.run_id AND tenant_id = current_tenant();
  IF TG_OP = 'INSERT' THEN
    IF NEW.journal_id IS NOT NULL THEN
      RAISE EXCEPTION 'overhead lines are written before their journals' USING ERRCODE = 'check_violation';
    END IF;
    SELECT * INTO x FROM overhead_compute(r.legal_entity_id, r.period_from, r.period_to, r.pool_account_id, r.target_account_id) c WHERE c.project_id = NEW.project_id;
    IF NOT FOUND OR (x.driver, x.share) IS DISTINCT FROM (NEW.driver, NEW.share) THEN
      RAISE EXCEPTION 'the overhead share of project % is not the database''s computation', NEW.project_id USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
  END IF;
  PERFORM p2p_only_changed(to_jsonb(OLD), to_jsonb(NEW), ARRAY['journal_id'], 'overhead line');
  IF OLD.journal_id IS NOT NULL OR NOT EXISTS (SELECT 1 FROM journals j WHERE j.id = NEW.journal_id AND j.source_type = 'OVERHEAD' AND j.source_ref = r.id::text AND j.project_id = NEW.project_id) THEN
    RAISE EXCEPTION 'an overhead line is bound once to its project''s OVERHEAD journal' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END$$;
CREATE TRIGGER overhead_lines_guard BEFORE INSERT OR UPDATE ON overhead_lines FOR EACH ROW EXECUTE FUNCTION overhead_lines_guard();

DO $$
DECLARE tbl text; owner text := current_user;
BEGIN
  FOREACH tbl IN ARRAY ARRAY['recurring_journals', 'recurring_journal_lines', 'recurring_journal_runs', 'accruals', 'overhead_runs', 'overhead_lines'] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', tbl);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', tbl);
    EXECUTE format('CREATE POLICY tenant_isolation ON %I USING (tenant_id = current_tenant()) WITH CHECK (tenant_id = current_tenant())', tbl);
    EXECUTE format('CREATE POLICY owner_maintenance ON %I TO %I USING (serk_maintenance_session()) WITH CHECK (serk_maintenance_session())', tbl, owner);
    EXECUTE format('REVOKE ALL ON %I FROM PUBLIC', tbl);
    EXECUTE format('GRANT SELECT, INSERT ON %I TO serk_app', tbl);
  END LOOP;
END$$;
GRANT UPDATE (status, next_run_on) ON recurring_journals TO serk_app;
